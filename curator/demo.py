"""`curator demo`: a `plant-support` instance made of the synthetic examples (curator.demo_files) and answered by
the `fake` backend with the stored responses of data/demo/llm/: the whole cycle, without an LLM and at no cost."""
from __future__ import annotations

import shutil
from pathlib import Path

import yaml

from curator import demo_files
from curator.init_cmd import init_instance
from curator.resources import resource

DEMO_TYPE = "plant-support"
FIXTURES_DIR = "demo-llm"           # inside the instance: the demo keeps working after an upgrade of the curator
ALIASES = {"REF5001": "tickets/7001", "line BL2": "plants/bl2"}

# What the demo shows, for the message at the end of `curator demo` (paths relative to ssot/).
WHAT_TO_LOOK_AT = [
    ("index.md", "the entry point of the SSOT: one index per concept type"),
    ("tickets/7001.md", "a service ticket: every statement cites its source (footnotes) and is 'pending' until "
                        "a person approves it; the wrong opening date in the fake answer was rejected, so it is absent"),
    ("problems/bl2/axis-in-overtemperature-alarm.md",
     "a problem put together from a mail thread, its PDF attachment and a WhatsApp chat, with a dated history"),
    ("procedures/drivesetup/change-node-address.md", "a procedure taken from a note of the owner"),
    ("conflicts.md", "contradictions between sources wait here for a human decision"),
]


def configure_demo(root: Path, fixtures: str | Path) -> None:
    """Fake backend with the stored responses, files taken at once, the pages of the demo manual, aliases."""
    path = root / "curator.yaml"
    cfg = yaml.safe_load(path.read_text(encoding="utf-8"))
    cfg["llm"]["backend"] = "fake"
    cfg["llm"]["fake_fixtures"] = str(fixtures)
    cfg["scan"] = {"stable_seconds": 0}        # the example files were just written: do not wait for them
    for s in cfg["sources"]:
        if s["match"].startswith("manuals/"):
            s["pages"] = {"demo manual*.pdf": "2"}
    cfg["aliases"] = dict(ALIASES)
    path.write_text("# Demo instance, generated by `curator demo`: synthetic files, fake LLM (no quota used)\n"
                    + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False, width=120),
                    encoding="utf-8", newline="\n")


def create_demo(target: Path) -> Path:
    """Creates the demo instance in `target` (which must not hold an instance); returns its root."""
    root = init_instance(target, DEMO_TYPE, "fake")
    shutil.copytree(resource("demo", "llm"), root / FIXTURES_DIR)
    configure_demo(root, FIXTURES_DIR)
    demo_files.build(root / "raw", extended=True)
    return root
