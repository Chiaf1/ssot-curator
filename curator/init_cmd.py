"""`curator init`: creates an instance (recipe §4) without any LLM."""
from __future__ import annotations

import subprocess
from pathlib import Path

import yaml

from curator import __version__
from curator.config import CONFIG_NAME, ConfigError, parse_config
from curator.resources import ROOT
from curator.typecheck import available_types, check_type, load_type

INSTANCE_GITIGNORE = """# Raw data and regenerable state: outside git (spec §4)
raw/
curated/
eval/
state/*
!state/decisions.jsonl
!state/forget.jsonl
"""

README = """# {name}

Instance of an SSOT managed by the curator (`ssot-curator`), type `{type}`.

- `raw/`: original sources (add them here; the curator only reads them). Folders: {folders}.
- `ssot/`: the SSOT in OKF format, written only by the curator. Read and search it, never edit it.
- `curated/`, `state/`: normalized texts and fact store, regenerable.

Commands: `curator doctor`, `curator run`, `curator status`, `curator validate`, `curator search "..."`.

The SSOT does not replace the original sources: safety procedures and parameters must always be checked
on the original.
"""


__all__ = ["available_types", "init_instance", "install_claude_files", "type_status", "type_summary"]


def type_summary(type_ref: str) -> str:
    """The first comment line of the type file (what the type is for)."""
    return load_type(type_ref).summary


def type_status(type_ref: str) -> str:
    """`tested` (exercised on real data) or `draft`."""
    return load_type(type_ref).status


def install_claude_files(target: Path, overwrite: bool = False) -> list[str]:
    """Claude Code in the instance (recipe §4): the permissions of the folder (.claude/settings.json: read-only
    commands allowed, the others ask, writing in raw/, curated/, state/, ssot/ and curator.yaml denied) and
    the `ssot` skill, which makes the agent the owner's interface to the curator."""
    src = ROOT / "templates" / "claude"
    written = []
    for p in sorted(src.rglob("*")):
        if p.is_file():
            out = target / ".claude" / p.relative_to(src)
            if out.exists() and not overwrite:
                continue
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(p.read_bytes())
            written.append(out.relative_to(target).as_posix())
    return written


def init_instance(target: Path, type_ref: str, backend: str, language: str | None = None) -> Path:
    """`type_ref`: an installed type, or the path of a type file of the owner (checked with the same rules)."""
    target = target.resolve()
    if (target / CONFIG_NAME).exists():
        raise FileExistsError(f"an instance already exists in {target}")
    loaded = load_type(type_ref)
    check = check_type(loaded.data)
    if not check.ok:
        raise ConfigError(f"the type {loaded.name} has errors (see `curator types --check`):\n- "
                          + "\n- ".join(check.errors))
    type_name = loaded.name
    cfg = loaded.data
    cfg.pop("status", None)
    cfg = {"schema_version": cfg.pop("schema_version"), "curator_version": __version__, **cfg}
    cfg["instance"]["name"] = target.name
    cfg["llm"]["backend"] = backend
    if language:
        cfg["instance"]["language"] = language
    parsed = parse_config(cfg)   # an invalid type configuration must not produce instances
    folders = parsed.raw_folders()
    for d in [f"raw/{f}" for f in folders] + ["curated", "ssot", "state", "eval"]:
        (target / d).mkdir(parents=True, exist_ok=True)
    (target / CONFIG_NAME).write_text(
        f"# Instance configuration, generated by `curator init --type {type_name}`\n"
        + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8", newline="\n")
    (target / ".gitignore").write_text(INSTANCE_GITIGNORE, encoding="utf-8", newline="\n")
    (target / ".gitattributes").write_text("* text=auto eol=lf\n", encoding="utf-8", newline="\n")
    (target / "README.md").write_text(README.format(name=target.name, type=type_name,
                                                    folders=", ".join(f"`raw/{f}/`" for f in folders) or "`raw/`"),
                                      encoding="utf-8", newline="\n")
    for f in ("decisions.jsonl", "forget.jsonl"):
        (target / "state" / f).touch()
    install_claude_files(target)
    if not (target / ".git").exists():
        subprocess.run(["git", "init", "-q", "-b", "main", str(target)], check=True)
    return target
